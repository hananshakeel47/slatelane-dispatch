create table if not exists public.carrier_document_records (
  id uuid primary key default gen_random_uuid(),
  onboarding_id uuid not null references public.carrier_onboardings(id) on delete cascade,
  carrier_id bigint,
  template_id uuid,
  document_type text not null,
  status text not null default 'requested',
  storage_bucket text,
  storage_path text,
  file_name text,
  mime_type text,
  file_size_bytes bigint,
  sha256 text,
  sent_to_email text,
  sent_at timestamptz,
  received_at timestamptz,
  signed_at timestamptz,
  approved_at timestamptz,
  expires_at timestamptz,
  signer_name text,
  signer_title text,
  rejection_reason text,
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint carrier_document_records_status_check
    check (status = any (array['requested','sent','received','signed','approved','expired','rejected','archived'])),
  constraint carrier_document_records_file_size_bytes_check
    check (file_size_bytes is null or file_size_bytes >= 0)
);

alter table public.carrier_document_records
  drop constraint if exists carrier_document_records_document_type_check;
alter table public.carrier_document_records
  add constraint carrier_document_records_document_type_check
  check (document_type = any (array[
    'dispatch_agreement','carrier_packet','w9','w8','coi','authority',
    'factoring_noa','factoring_agreement','limited_power_of_attorney',
    'payment_setup','rate_confirmation','pod','broker_packet','other'
  ]));

create table if not exists public.carrier_document_events (
  id bigint generated by default as identity primary key,
  onboarding_id uuid not null references public.carrier_onboardings(id) on delete cascade,
  document_id uuid,
  event_type text not null,
  from_status text,
  to_status text,
  actor text,
  note text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.carrier_portal_access (
  id uuid primary key default gen_random_uuid(),
  onboarding_id uuid not null references public.carrier_onboardings(id) on delete cascade,
  email text not null check (email = lower(btrim(email))),
  status text not null default 'active' check (status in ('active','revoked')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  revoked_at timestamptz,
  last_login_at timestamptz,
  unique (onboarding_id, email)
);

create table if not exists public.carrier_portal_login_challenges (
  id uuid primary key,
  email_hash text not null,
  ip_hash text not null,
  code_hash text not null,
  attempts integer not null default 0 check (attempts >= 0 and attempts <= 5),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  consumed_at timestamptz
);

create table if not exists public.carrier_portal_sessions (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  email text not null check (email = lower(btrim(email))),
  ip_hash text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz
);

create table if not exists public.carrier_portal_audit_events (
  id uuid primary key default gen_random_uuid(),
  onboarding_id uuid not null references public.carrier_onboardings(id) on delete cascade,
  portal_access_id uuid references public.carrier_portal_access(id) on delete set null,
  session_id uuid references public.carrier_portal_sessions(id) on delete set null,
  document_id uuid references public.carrier_document_records(id) on delete set null,
  event_type text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists carrier_portal_access_email_status_idx
  on public.carrier_portal_access (email, status);
create index if not exists carrier_portal_access_onboarding_idx
  on public.carrier_portal_access (onboarding_id, status);
create index if not exists carrier_portal_challenges_email_created_idx
  on public.carrier_portal_login_challenges (email_hash, created_at desc);
create index if not exists carrier_portal_challenges_ip_created_idx
  on public.carrier_portal_login_challenges (ip_hash, created_at desc);
create index if not exists carrier_portal_sessions_expiry_idx
  on public.carrier_portal_sessions (expires_at) where revoked_at is null;
create index if not exists carrier_portal_audit_onboarding_created_idx
  on public.carrier_portal_audit_events (onboarding_id, created_at desc);
create index if not exists carrier_document_records_onboarding_type_created_idx
  on public.carrier_document_records (onboarding_id, document_type, created_at desc);

