-- Production already has the carrier onboarding and document vault tables.
-- These compatible definitions let isolated environments start cleanly while
-- leaving existing production relations intact.
create table if not exists public.carrier_onboardings (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid,
  carrier_id bigint,
  company_name text not null,
  dot_number bigint,
  mc_number text,
  primary_contact_name text,
  primary_contact_email text,
  primary_contact_phone text,
  status text not null default 'draft',
  agreement_status text not null default 'not_sent',
  agreement_signed_at timestamptz,
  load_board_access_status text not null default 'not_requested',
  load_board_provider text,
  dispatch_fee_type text,
  dispatch_fee_value numeric,
  minimum_rate_per_mile numeric,
  weekly_revenue_target numeric,
  preferred_lanes text[] not null default '{}',
  regions_to_avoid text[] not null default '{}',
  preferred_states text[] not null default '{}',
  home_time_notes text,
  operating_notes text,
  factoring_company text,
  insurance_company text,
  insurance_expiration date,
  onboarding_completed_at timestamptz,
  activated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
