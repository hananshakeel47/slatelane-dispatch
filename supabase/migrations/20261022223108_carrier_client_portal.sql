        (select count(*) from public.carrier_document_records d where d.onboarding_id=o.id and d.status <> 'archived')::bigint as document_count,
        exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='dispatch_agreement' and d.status in ('signed','approved')) as agreement_ready,
        exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='carrier_packet' and d.status in ('signed','approved')) as carrier_packet_ready,
        exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type in ('w9','w8') and d.status in ('received','signed','approved')) as tax_form_ready,
        exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='coi' and d.status in ('received','approved')) as insurance_ready,
        exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='authority' and d.status in ('received','approved')) as authority_ready,
        exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type in ('factoring_noa','factoring_agreement') and d.status in ('received','approved')) as factoring_ready,
        array_remove(array[
          case when not exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='dispatch_agreement' and d.status in ('signed','approved')) then 'dispatch_agreement' end,
          case when not exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='carrier_packet' and d.status in ('signed','approved')) then 'carrier_packet' end,
          case when not exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type in ('w9','w8') and d.status in ('received','signed','approved')) then 'tax_form' end,
          case when not exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='coi' and d.status in ('received','approved')) then 'coi' end,
          case when not exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='authority' and d.status in ('received','approved')) then 'authority' end,
          case when not exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type in ('factoring_noa','factoring_agreement') and d.status in ('received','approved')) then 'factoring' end
        ], null) as missing_documents,
        (
          exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='dispatch_agreement' and d.status in ('signed','approved'))
          and exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='carrier_packet' and d.status in ('signed','approved'))
          and exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='w9' and d.status in ('received','signed','approved'))
          and exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='coi' and d.status in ('received','approved'))
          and exists(select 1 from public.carrier_document_records d where d.onboarding_id=o.id and d.document_type='authority' and d.status in ('received','approved'))
        ) as broker_packet_ready
      from public.carrier_onboardings o
    $view$;
  end if;
end
$$;

create or replace function public.verify_carrier_portal_login_code(
  p_challenge_id uuid,
  p_email_hash text,
  p_code_hash text
) returns boolean
language plpgsql
security invoker
set search_path = public, pg_temp
as $function$
begin
  update public.carrier_portal_login_challenges
  set consumed_at = now()
  where id = p_challenge_id
    and email_hash = p_email_hash
    and code_hash = p_code_hash
    and consumed_at is null
    and expires_at > now()
    and attempts < 5;

  if found then
    return true;
  end if;

  update public.carrier_portal_login_challenges
  set attempts = attempts + 1
  where id = p_challenge_id
    and email_hash = p_email_hash
    and consumed_at is null
    and expires_at > now()
    and attempts < 5;

  return false;
end;
$function$;

revoke all on function public.verify_carrier_portal_login_code(uuid, text, text) from public, anon, authenticated;
grant execute on function public.verify_carrier_portal_login_code(uuid, text, text) to service_role;

